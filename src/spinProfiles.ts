// Каждая точка: [доля времени 0..1, доля пройденного угла 0..1].
// Между точками считаем монотонным кубическим сплайном, поэтому скорость плавная и стрелка не откатывается назад.

export type SpinMode = 'normal' | 'fast'

export type SpinProfile = {
  turns: number       // полных оборотов до остановки (поверх угла остановки)
  motionMs: number    // сколько стрелка реально движется
  resultMs: number    // через сколько после старта показываем итог (NO PROBLEM / Upgrade successful!)
  holdMs: number      // сколько итог висит, пока колесо не вернётся в обычный вид
  startSound: 'start' | 'startFast' // какой файл играет на старте крутки
  soundLeadMs: number // насколько стартовый звук начинается раньше движения стрелки
                      // (если это больше паузы после клика, самое начало звука пропускается, а остальное идёт вовремя)
  tickTimesMs: number[] // моменты тиков: мс от начала стартового звука (сняты с записи оригинала)
  points: [number, number][]
}

